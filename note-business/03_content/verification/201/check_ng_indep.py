#!/usr/bin/env python3
"""201 NG例（前置きなしの短い頼み方）の独立実行（claude -p）の出力を分類する。結果は check_ng_indep-result.md

- 対象：prompts/ng-NN.run1.txt。場面18は3回とも比べられる文面が出なかったため、分類の対象外（下の NG18_NOTE）
- 機械：空欄（【 】・〇〇・◯・（記入）・〔○…〕・△△・□□）、頼んでいない前後の説明と別の案、計算（前月比・%）、英語の作業メモ、実行環境についての記述
- 目視：入力にない約束・事実・日付・評価・決まりが足されたか（下の ADDED。引用が出力に含まれるかを確かめる）
"""
import re, pathlib, sys

here = pathlib.Path(__file__).parent
P = here / "prompts"
NG18_NOTE = ("3回とも、比べられる文面が出なかった。run1（11/8、リポジトリの中で実行）は「ツールの実行結果が取得できない」「リポジトリ内の請求書関連ファイル」など実行環境についての記述と、"
             "それに合わせたひな形。run2（11/13、リポジトリの外で実行）はAPIのエラー（safeguards、出力なし）。run3（11/13、同）はファイルを探すコマンドの呼び出しの文字列だけ。"
             "いずれも claude -p（コマンドで動かすClaude Code）の環境に由来し、チャットの画面での出力の代わりにならないため、記事にはNG例を載せない")

BLANK = re.compile(r"【[^】]*】|〇{1,}|◯|○|（記入）|△△|□□")
EXTRA = re.compile(r"(?m)^(---|\*\*補足|補足|\*\*ポイント|\*\*送るときのポイント|\*\*書くときのポイント|\*\*確認したい点|### 送る前に|\*\*教えていただきたいこと)|"
                   r"教えていただければ|教えてもらえれば|お知らせください|調整します|調整も可能|お作りします|版が必要でしたら|以下、|の文例です|のテンプレートです|たたき台です|例文です|の文面です|の案です|今週の週報です|やわらかくした例です")
DRAFTS = re.compile(r"案1|案2|短縮版|まとめて送る場合|個別に送る場合")
CALC = re.compile(r"前月比|[+＋]\d+件|\d+(\.\d+)?%|差は\d+件")
ENGLISH = re.compile(r"(?m)^[^\n]*[A-Za-z]{4,}(?: [A-Za-z]{2,}){3,}")
ENV = re.compile(r"リポジトリ|作業ディレクトリ|ツールの実行|コマンドの出力|コマンドを何度か")

# 目視で「入力にない約束・事実・日付・評価・決まりが足された」と判断したもの（出力からの引用）
ADDED = {
    1: ["共有リンク等でも問題ございません"],
    2: ["13:00〜17:00", "所要時間は1時間程度", "貴社へお伺いする形、またはオンラインのいずれでも対応可能です"],
    4: ["再発防止に努めてまいります", "可能な限り対応させていただきます"],
    5: ["送信前の確認を徹底いたします"],
    6: ["社内で慎重に検討いたしましたが"],
    7: ["大変有意義な時間となりました", "本日はご多忙のところ"],
    8: ["フォーマットは添付のテンプレートをご利用ください"],
    9: ["駐車場の件 議題準備", "大掃除の段取り・周知", "メモから想定して追加した項目"],
    11: ["11月8日（日）"],
    12: ["2026年11月2日〜11月8日", "年末調整書類の内容確認（不備があれば差し戻し）", "発行した請求書の入金状況の確認"],
    13: ["保守業者に修理を依頼済みです", "印刷キューに残っているジョブは、お手数ですが各自で削除をお願いします"],
    14: ["滞りなく進めています", "必要に応じて督促します", "+7件(+5.8%)", "差は8件です"],
    15: ["セキュリティの強化", "コストの抑制", "月あたり約【◯】時間の作業時間短縮が見込めます"],
    16: ["【所属長】の承認後に購入してください", "承認前に購入した場合、経費として精算できないことがあります", "同じ目的の購入を分けて5,000円未満にすることはできません"],
    17: ["ご到着が遅れそうな場合は、下記までご連絡ください", "直近の「11月26日（木）」"],
    20: ["現在、社内で生産・在庫の状況を確認しております", "納期のみ先にお知らせいたします"],
}
# 空欄の印が、文面ではなく文面のあとの補足（例の説明）の中にしかないもの
BLANK_IN_NOTE_ONLY = {12: "〇は補足の「〇名中〇名分」の例の中だけで、文面には空欄がない"}
# 足されたものとは別に、意味が変わったもの
CHANGED = {19: ["お手すきの際にご対応いただけますと助かります", "原本でご提出いただけますと幸いです"]}
# 足されたと数えなかったもの（理由）
NOT_COUNTED = {
    3: "「改めてお送りいたします」（届いていない場合の再送の申し出）は、事実や約束として害が小さいため数えなかった",
    10: "頼んでいない項目（未提出者リスト、分担表の共有期限）は【 】の空欄として出たため、空欄に数えた",
    19: "意味が変わった（任意のお願いに読める）。足されたものとしては数えなかった",
}


def path(no):
    return P / f"ng-{no:02d}.run1.txt"


lines = ["# 201 NG例（前置きなしの短い頼み方）の独立実行の分類", "",
         "分類：check_ng_indep.py（2026-11-13）。各場面1回の独立実行（claude -p）の出力。", ""]
cnt = {"足された": [], "空欄": [], "説明・別の案": [], "意味が変わった": [], "計算": [], "英語の作業メモ": [], "実行環境の記述": []}
missing = []
for no in range(1, 21):
    f = path(no)
    if no == 18:
        missing.append(no)
        lines.append(f"- 場面18：分類の対象外。{NG18_NOTE}")
        continue
    t = f.read_text(encoding="utf-8")
    for q in ADDED.get(no, []) + CHANGED.get(no, []):
        if q not in t:
            sys.exit(f"場面{no}の引用が出力にない: {q}")
    blanks = [] if no in BLANK_IN_NOTE_ONLY else BLANK.findall(t)
    extra = sorted(set(m.group(0).strip() for m in EXTRA.finditer(t)))
    drafts = sorted(set(DRAFTS.findall(t)))
    calc = sorted(set(m.group(0) for m in CALC.finditer(t)))
    eng = bool(ENGLISH.search(t))
    env = sorted(set(ENV.findall(t)))
    flags = {"足された": bool(ADDED.get(no)), "空欄": bool(blanks), "説明・別の案": bool(extra or drafts),
             "意味が変わった": no in CHANGED, "計算": bool(calc), "英語の作業メモ": eng, "実行環境の記述": bool(env)}
    for k, v in flags.items():
        if v:
            cnt[k].append(no)
    lines.append(f"- 場面{no}（{f.name}）：足された{ADDED.get(no) or 'なし'}／空欄{len(blanks)}か所／前後の説明{extra or 'なし'}／別の案{drafts or 'なし'}"
                 f"／計算{calc or 'なし'}／意味が変わった{CHANGED.get(no) or 'なし'}／英語の作業メモ{'あり' if eng else 'なし'}／実行環境の記述{env or 'なし'}"
                 + (f"（{NOT_COUNTED[no]}）" if no in NOT_COUNTED else "") + (f"（{BLANK_IN_NOTE_ONLY[no]}）" if no in BLANK_IN_NOTE_ONLY else ""))
n = 20 - len(missing)
lines += ["", f"## 集計（出力があった{n}場面）"] + [f"- {k}：{len(v)}場面 {v}" for k, v in cnt.items()]
lines += ["", "## メモ",
          "- 空欄は、11/8〜9の執筆の作業セッション内の出力では「〇〇」だったが、独立実行では【 】の形が多かった（〇〇・◯・（記入）・〔○…〕も含めて数えた）",
          "- 場面4の冒頭と場面12の補足3つ目は、実行環境（claude -p）に由来する記述（英語の作業メモ、ファイルへの保存、リポジトリ・ツール）。記事の抜粋には使っていない",
          "- 場面2・11・12・17は、AIが実行した日（2026-11-08）を基準に日付や曜日を決めた"]
(here / "check_ng_indep-result.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
