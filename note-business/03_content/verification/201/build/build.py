def excerpt(no):
    src = ng_output(no).splitlines()
    spec = NG_EXCERPT[no]
    if isinstance(spec, tuple):
        _, first, last = spec
        assert first in src and last in src, (no, first, last)
        return "\n".join(src[src.index(first):src.index(last) + 1])
    idx = []
    for l in spec:
        if l not in src:
            sys.exit(f"場面{no}のNG抜粋が出力にない: {l}")
        idx.append(src.index(l))
    assert idx == sorted(idx), f"場面{no}の抜粋の順番が出力と違う"
    out = [spec[0]]
    for prev, cur, l in zip(idx, idx[1:], spec[1:]):
        between = [x for x in src[prev + 1:cur] if x.strip()]
        out.append(("（中略）\n" if between else "") + l)
    return "\n".join(out)


def problems(no):
    ng = ng_output(no)
    for p in NG_PROBLEMS[no]:
        for q in re.findall(r"「([^「」]+)」", p):
            if q not in ng and q not in ng_prompt(no) and q not in QUOTE_OK:   # 出力か、頼んだ文の言葉
                sys.exit(f"場面{no}の問題点の引用が出力にない: {q}")
    return NG_PROBLEMS[no]


def ng_label(no):
    return NG_LABEL.get(no, "「" + ng_prompt(no) + "」とだけ頼んだ")


def checks(no):
    return S[no]["checks"] + CHECKS_EXTRA.get(no, [])


def ng_part(no, label_suffix):
    if no == 18:
        return [NG18_TEXT, "", "送る前の確認点", ""] + [f"- {c}" for c in checks(no)]
    parts = [f"NG例：前置きなしで{ng_label(no)}出力の{label_suffix}です。", "", block(excerpt(no)), "", "問題点", ""]
    parts += [f"- {p}" for p in problems(no)]
    parts += ["", "送る前の確認点", ""] + [f"- {c}" for c in checks(no)]
    return parts


